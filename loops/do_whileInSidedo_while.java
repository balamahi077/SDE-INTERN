package loops;

public class do_whileInSidedo_while {
    public static void main(String[] args) {

        int index = 1;
        do
        {
            int java = 1;
            do{
                System.out.print("* ");
                java++;
            }while(java <= 4);

            System.out.println();
            index++;
        }while(index <= 3);

    }
}
