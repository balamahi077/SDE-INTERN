package Chellenges;

public class Int_Float {
    public static void main(String[] args) {

        int num1 = 45;
        int num2 = 25;
        float intResult = (float)num1 / num2;

        System.out.println("Integer Division = " + intResult);
        System.out.println((float)num1 / num2);

        System.out.println("--------------------------------------------");

        float num3 = 2.5f;
        float num4 = 4.5f;
        int floatResult = (int)num3 / (int)num4;

        System.out.println("Float Division  = " + floatResult);
        System.out.println( (int)num3 / (int)num4);
    }
}
